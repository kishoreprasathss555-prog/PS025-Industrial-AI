
import { useCallback, useEffect, useState } from 'react'
import {
  Activity,
  RefreshCw,
  Wifi,
  Thermometer,
  Gauge,
  Zap,
} from 'lucide-react'
import api from '../api/client'

interface PredictionResult {
  rul: number
  health_percentage: number
  failure_probability: number
  risk_level: string
  wear_estimate: number
  is_simulated: boolean
  confidence: number
}

interface SensorReading {
  device: string
  mode: string
  connected: boolean
  timestamp: string
  toolWear: number
  operatingTime: number
  cuttingTemp: number
  vibration: number
  cuttingForce: number
  feedRate: number
  spindleSpeed: number
  powerConsumption: number
}

export default function SimulatorPage() {
  const [reading, setReading] = useState<SensorReading | null>(null)
  const [loading, setLoading] = useState(false)
  const [error, setError] = useState('')
  const [prediction, setPrediction] = useState<PredictionResult | null>(null)
  const [predicting, setPredicting] = useState(false)

  const fetchReading = useCallback(async () => {
    setLoading(true)
    setError('')

    try {
      const response = await api.get<SensorReading>('/simulator/readings')
      setReading(response.data)
      setPrediction(null)
    } catch {
      setError('Simulator API unavailable. Check the backend server.')
    } finally {
      setLoading(false)
    }
  }, [])

  const runAIPrediction = async () => {
    if (!reading) return

    setPredicting(true)
    setError('')
    setPrediction(null)

    try {
      const response = await api.post<PredictionResult>(
        '/predictions/predict',
        {
          toolType: 'End Mill',
          toolId: 'TL-001',
          toolWear: reading.toolWear,
          operatingTime: reading.operatingTime,
          cuttingTemp: reading.cuttingTemp,
          vibration: reading.vibration,
          cuttingForce: reading.cuttingForce,
          feedRate: reading.feedRate,
          spindleSpeed: reading.spindleSpeed,
          powerConsumption: reading.powerConsumption,
          depthOfCut: 2.5,
        }
      )

      setPrediction(response.data)
    } catch {
      setError('AI Prediction failed. Check the backend server.')
    } finally {
      setPredicting(false)
    }
  }

  useEffect(() => {
    fetchReading()
  }, [fetchReading])

  const sensors = reading
    ? [
        { label: 'Tool Wear', value: `${reading.toolWear}%`, icon: Gauge },
        { label: 'Operating Time', value: `${reading.operatingTime} min`, icon: Activity },
        { label: 'Cutting Temperature', value: `${reading.cuttingTemp} °C`, icon: Thermometer },
        { label: 'Vibration', value: `${reading.vibration} g`, icon: Activity },
        { label: 'Cutting Force', value: `${reading.cuttingForce} N`, icon: Zap },
        { label: 'Feed Rate', value: `${reading.feedRate} mm/min`, icon: Gauge },
        { label: 'Spindle Speed', value: `${reading.spindleSpeed} RPM`, icon: RefreshCw },
        { label: 'Power Consumption', value: `${reading.powerConsumption} kW`, icon: Zap },
      ]
    : []

  return (
    <div className="space-y-6">
      <div className="flex flex-wrap items-center justify-between gap-3">
        <div>
          <h1 className="text-2xl font-bold text-white">
            Virtual ESP32 Simulator
          </h1>
          <p className="mt-1 text-sm text-slate-400">
            PS-025 simulated CNC sensor readings
          </p>
        </div>

        <button
          onClick={fetchReading}
          disabled={loading}
          className="flex items-center gap-2 rounded-lg bg-cyan-500 px-4 py-2 text-sm font-semibold text-slate-950 disabled:opacity-50"
        >
          <RefreshCw size={16} className={loading ? 'animate-spin' : ''} />
          Refresh Data
        </button>
      </div>

      <div className="rounded-xl border border-amber-500/30 bg-amber-500/10 p-4">
        <div className="flex items-center gap-2 font-semibold text-amber-400">
          <Activity size={18} />
          SIMULATED DATA – NOT REAL HARDWARE
        </div>
        <p className="mt-1 text-sm text-slate-300">
          Sensor readings are generated by software. No physical ESP32 or CNC machine is connected.
        </p>
      </div>

      <div className="rounded-xl border border-indigo-500/30 bg-indigo-500/10 p-4">
        <h2 className="text-lg font-semibold text-white">
          AI Tool-Life Prediction
        </h2>
        <p className="mt-1 text-sm text-slate-300">
          Send virtual ESP32 sensor readings to the Random Forest model.
        </p>

        <button
          onClick={runAIPrediction}
          disabled={!reading || predicting}
          className="mt-3 rounded-lg bg-indigo-500 px-4 py-2 text-sm font-semibold text-white disabled:opacity-50"
        >
          {predicting ? 'Predicting...' : 'Run AI Prediction'}
        </button>
      </div>

      <div className="rounded-xl border border-slate-700 bg-slate-900 p-4">
        <div className="flex flex-wrap items-center justify-between gap-3">
          <div>
            <p className="text-xs text-slate-400">Virtual Device</p>
            <h2 className="mt-1 text-lg font-semibold text-white">
              {reading?.device || 'VIRTUAL-ESP32-01'}
            </h2>
          </div>

          <div className="flex items-center gap-2 text-sm text-emerald-400">
            <Wifi size={17} />
            {reading?.connected ? 'Connected (Virtual)' : 'Waiting for data'}
          </div>
        </div>

        <p className="mt-2 text-xs text-slate-500">
          Mode: {reading?.mode || 'SIMULATED'}
        </p>
      </div>

      {error && (
        <div className="rounded-lg border border-red-500/30 bg-red-500/10 p-3 text-sm text-red-300">
          {error}
        </div>
      )}

      {prediction && (
        <div className="space-y-4 rounded-xl border border-indigo-500/30 bg-slate-900 p-4">
          <h2 className="text-lg font-bold text-white">
            AI Prediction Results
          </h2>

          <p className="text-xs font-semibold text-amber-400">
            SIMULATED ML PREDICTION
          </p>

          <div className="grid grid-cols-1 gap-4 sm:grid-cols-3">
            <div>
              <p className="text-sm text-slate-400">Remaining Useful Life</p>
              <p className="text-2xl font-bold text-cyan-400">
                {prediction.rul} min
              </p>
            </div>

            <div>
              <p className="text-sm text-slate-400">Tool Health</p>
              <p className="text-2xl font-bold text-emerald-400">
                {prediction.health_percentage}%
              </p>
            </div>

            <div>
              <p className="text-sm text-slate-400">Failure Probability</p>
              <p className="text-2xl font-bold text-orange-400">
                {prediction.failure_probability}%
              </p>
            </div>
          </div>

          <p className="text-sm text-slate-300">
            Risk Level:{' '}
            <span className="font-bold uppercase">
              {prediction.risk_level}
            </span>
          </p>

          <p className="text-xs text-slate-500">
            Wear Estimate: {prediction.wear_estimate}%
          </p>
        </div>
      )}

      <div className="grid grid-cols-1 gap-4 sm:grid-cols-2 xl:grid-cols-4">
        {sensors.map((sensor) => {
          const Icon = sensor.icon

          return (
            <div
              key={sensor.label}
              className="rounded-xl border border-slate-700 bg-slate-900 p-4"
            >
              <div className="flex items-center justify-between">
                <span className="text-sm text-slate-400">
                  {sensor.label}
                </span>
                <Icon size={18} className="text-cyan-400" />
              </div>

              <p className="mt-3 text-2xl font-bold text-white">
                {sensor.value}
              </p>
            </div>
          )
        })}
      </div>

      {reading && (
        <p className="text-xs text-slate-500">
          Last updated: {new Date(reading.timestamp).toLocaleString()}
        </p>
      )}
    </div>
  )
}
